test('timingOf counts to the start, then to the end, then past it', () => {
  const day = (iso: string) => Date.UTC(Number(iso.slice(0, 4)), Number(iso.slice(5, 7)) - 1, Number(iso.slice(8))) / 86_400_000
  expect(timingOf('2026-10-23', '2026-11-05', day('2026-10-13'))).toEqual({ kind: 'starts', days: 10 })
  expect(timingOf('2026-10-23', '2026-11-05', day('2026-10-28'))).toEqual({ kind: 'left', days: 8 })
  expect(timingOf('2026-10-23', '2026-11-05', day('2026-11-05'))).toEqual({ kind: 'left', days: 0 })
  expect(timingOf('2026-10-23', '2026-11-05', day('2026-11-07'))).toEqual({ kind: 'over', days: 2 })
  expect(timingOf(null, null, 0)).toBeNull()
})

