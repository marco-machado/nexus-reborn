test('the bar is full only when done and empty only at zero', () => {
  const p = (done: number, total: number) => ({ done, total, review: 0, inProgress: 0, blocked: 0 })
  expect(filledCells(p(0, 11))).toBe(0)
  expect(filledCells(p(1, 30))).toBe(1)
  expect(filledCells(p(10, 11))).toBe(9)
  expect(filledCells(p(11, 11))).toBe(10)
})

test('segments give every status a cell and keep one empty while a story has not started', () => {
  expect(segments({ done: 8, review: 1, inProgress: 1, blocked: 1, total: 11 })).toEqual({
    done: 7,
    review: 1,
    inProgress: 1,
    blocked: 1,
  })
  expect(segments({ done: 5, review: 0, inProgress: 1, blocked: 0, total: 11 })).toEqual({
    done: 5,
    review: 0,
    inProgress: 1,
    blocked: 0,
  })
  expect(segments({ done: 10, review: 0, inProgress: 0, blocked: 0, total: 11 })).toEqual({
    done: 9,
    review: 0,
    inProgress: 0,
    blocked: 0,
  })
  expect(segments({ done: 1, review: 0, inProgress: 2, blocked: 0, total: 3 })).toEqual({
    done: 3,
    review: 0,
    inProgress: 7,
    blocked: 0,
  })
})

