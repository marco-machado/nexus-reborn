test('a script that will not start leaves the band to the engine and keeps the minute refresh', async ($, on) => {
  const clock = mock.clock(on, { now: TODAY })
  const rejects = { current: true }
  on('ui.render', { component: 'AbovePrompt' }, ($, e) => {
    const { Text } = $.ui.resolve(e)
    return <Text>engine band</Text>
  })
  start(on)
  on('process.run', () => {
    if (rejects.current) throw new Error('timed out')
    return {
      value: { exitCode: 0, stdout: STATUS, stderr: '', isStdoutTruncated: false, isStderrTruncated: false },
    }
  })
  files(on, { current: repo(yaml('done')) })
  await $.session.start({ cwd: '/repo', surface: 'terminal', isInteractive: true })

  const before = await $.ui.mount({ ...BAND, surface: 'terminal' })
  expect(await before.find({ text: /Production/ })).toBeUndefined()
  expect((await before.find({ type: 'Text' }))?.text).toBe('engine band')
  await before.unmount()

  rejects.current = false
  await clock.advance(60_000)

  const after = await $.ui.mount({ ...BAND, surface: 'terminal' })
  expect(await text(after)).toBe('Production·standard › World Network › Sprint 2  ✓ complete 2/2')
  await after.unmount()
})

