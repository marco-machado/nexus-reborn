// The script's output as each run answers it; `null` is a failed run.
const script = (on: On, outputs: { current: string | null }) =>
  on('process.run', () => ({
    value: {
      exitCode: outputs.current === null ? 1 : 0,
      stdout: outputs.current ?? '',
      stderr: '',
      isStdoutTruncated: false,
      isStderrTruncated: false,
    },
  }))

// The repo's files by path: text, or `null` there but unreadable; absent, absent.
const files = (on: On, tree: { current: Record<string, string | null> }) => {
  on('fs.exists', ($, e) => ({ value: e.path in tree.current }))
  on('fs.read', ($, e) => {
    const text = tree.current[e.path]
    if (typeof text !== 'string') throw new Error('EACCES')
    return { value: text }
  })
}

const start = (on: On) => {
  on('session.start', () => ({ cwd: '/repo' }))
  on('ui.open', () => ({ value: { isPlaced: true } }))
}

type Engine = Parameters<Extract<Parameters<typeof test>[1], (...args: never[]) => unknown>>[0]

const boot = async ($: Engine, on: On, out: string | null, tree: Record<string, string | null>) => {
  mock.clock(on, { now: TODAY })
  start(on)
  script(on, { current: out })
  files(on, { current: tree })
  await $.session.start({ cwd: '/repo', surface: 'terminal', isInteractive: true })
}

